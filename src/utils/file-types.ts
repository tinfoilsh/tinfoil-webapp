/**
 * File type detection for attachment previews.
 */

// Financial data extensions that can be read as plain text
const FINANCIAL_EXTENSIONS = [
  '.qfx',
  '.qif',
  '.ofx',
  '.ifs',
  '.qbo',
  '.qbx',
  '.bai',
  '.bai2',
  '.mt940',
  '.sta',
  '.tsv',
  '.ics',
  '.vcf',
]

// Plain text / code extensions that can be read directly in the browser
const PLAIN_TEXT_EXTENSIONS = [
  '.txt',
  '.md',
  '.py',
  '.js',
  '.jsx',
  '.ts',
  '.tsx',
  '.css',
  '.json',
  '.xml',
  '.yaml',
  '.yml',
  '.toml',
  '.sh',
  '.bash',
  '.rb',
  '.java',
  '.cpp',
  '.c',
  '.h',
  '.hpp',
  '.go',
  '.rs',
  '.swift',
  '.kt',
  '.kts',
  '.r',
  '.sql',
  '.lua',
  '.pl',
  '.php',
  '.cs',
  '.csx',
  '.vb',
  '.fs',
  '.fsx',
  '.scala',
  '.dart',
  '.ex',
  '.exs',
  '.erl',
  '.hs',
  '.ml',
  '.mli',
  '.clj',
  '.cljs',
  '.groovy',
  '.gradle',
  '.m',
  '.mm',
  '.zig',
  '.nim',
  '.jl',
  '.ps1',
  '.psm1',
  '.bat',
  '.cmd',
  '.asm',
  '.s',
  '.proto',
  '.graphql',
  '.gql',
  '.tf',
  '.tfvars',
  '.dockerfile',
  '.makefile',
  '.cmake',
  '.tex',
  '.bib',
  '.svg',
  '.properties',
  '.lock',
  '.diff',
  '.patch',
  '.env',
  '.ini',
  '.cfg',
  '.conf',
  '.log',
  '.rtf',
  ...FINANCIAL_EXTENSIONS,
]

export function isPlainTextFile(filename: string): boolean {
  const lowerFilename = filename.toLowerCase()
  return PLAIN_TEXT_EXTENSIONS.some((ext) => lowerFilename.endsWith(ext))
}
